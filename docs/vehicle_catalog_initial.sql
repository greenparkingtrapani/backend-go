-- Green Parking: initial vehicle catalogue proposal (30 cars / 20 motorcycles)
-- Apply only after reviewing data and migration strategy; this file is NOT applied automatically.
-- Dimensions are indicative, vary by year/trim, and must not be treated as certified measurements.
-- Model images should be original or properly licensed and stored via image_url.
CREATE TABLE IF NOT EXISTS vehicle_catalog (
  id BIGSERIAL PRIMARY KEY,
  kind TEXT NOT NULL CHECK (kind IN ('car', 'motorcycle')),
  brand TEXT NOT NULL,
  model TEXT NOT NULL,
  parking_category TEXT NOT NULL CHECK (parking_category IN ('car','sedan','suv','motorcycle','naked','custom','adventure','sport','scooter','maxi-scooter')),
  length_m NUMERIC(4,2),
  width_m NUMERIC(4,2),
  image_url TEXT,
  image_license TEXT,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (kind,brand,model)
);
CREATE INDEX IF NOT EXISTS idx_vehicle_catalog_kind_brand ON vehicle_catalog(kind,brand);
